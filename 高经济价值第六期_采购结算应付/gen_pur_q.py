def sheet(title, headers, rows, widths=None, banner=None, comment=None):
    ws = wb.create_sheet(title)
    if banner:
        ws.append([banner])
        ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
        c = ws.cell(row=1, column=1)
        c.font = RED_FONT
        c.alignment = Alignment(horizontal='left', vertical='center', wrap_text=True)
        ws.row_dimensions[1].height = 26
        ws.append([])
    hr = ws.max_row + 1
    ws.append(headers)
    for r in rows:
        ws.append(r)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=hr, column=c)
        cell.font = HDR_FONT
        cell.fill = HDR_FILL
        cell.alignment = CENTER
        cell.border = BORDER
        ws.column_dimensions[get_column_letter(c)].width = (widths or {}).get(c, 14)
    for row in ws.iter_rows(min_row=hr + 1, max_row=ws.max_row, max_col=len(headers)):
        for cell in row:
            cell.font = BODY
            cell.alignment = WRAP
            cell.border = BORDER
    ws.freeze_panes = ws.cell(row=hr + 1, column=1)
    if comment:
        ref, txt = comment
        cm = Comment(txt, '财务部')
        cm.width, cm.height = 360, 110
        ws[ref].comment = cm
    return ws


