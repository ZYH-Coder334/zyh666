import random
random.seed(2024)

activities = []
# 280项处理活动
purposes = ['订单履约', '营销推送', '风控反欺诈', '客服售后', '骑手调度', '商户结算', '信用评估', '广告投放', '数据分析', '产品优化']
data_cats = ['基本资料', '订单数据', '位置信息', '设备信息', '支付信息', '交易记录', '行为日志', '通讯录', '身份信息', '生物识别']
legal_bases = ['履行合同所必需', '履行合同所必需', '履行合同所必需', '同意', '同意', '法定职责', '法定义务', '正当利益']
storage_locs = ['国内华东', '国内华北', '国内华南', '新加坡', '国内华东+新加坡']

# 设计陷阱分布
# 合法性基础错误：约30项（把必要信息用了同意，或把非必要信息用了履行合同）
legal_basis_error_idx = set(random.sample(range(280), 30))
# 出境未评估：约15项
cross_border_unassessed_idx = set(random.sample(range(280), 15))
# 未告知：约20项
unnotified_idx = set(random.sample(range(280), 20))
# 缺单独同意（敏感信息未单独同意）：约25项
no_separate_consent_idx = set(random.sample(range(280), 25))
# 保留期限超期：约18项
retention_exceeded_idx = set(random.sample(range(280), 18))
# 反直觉正常项：约30项（看似问题实则合法）
normal_trap_idx = set(random.sample(range(280), 30))

for i in range(280):
    idx = i + 1
    purpose = random.choice(purposes)
    cat = random.choice(data_cats)
    field_count = random.randint(3, 15)
    is_sensitive = '是' if cat in ['位置信息', '支付信息', '身份信息', '生物识别', '通讯录'] and random.random() > 0.5 else '否'
    legal_basis = random.choice(legal_bases)
    storage = random.choice(storage_locs)
    cross_border = '是' if storage == '新加坡' or storage == '国内华东+新加坡' else '否'
    notified = '是'
    separate_consent = '不适用' if is_sensitive == '否' else random.choice(['是', '否'])
    retention = random.choice(['6个月', '1年', '2年', '3年', '5年', '永久'])
    status = '合规'
    note = ''

    if idx in legal_basis_error_idx:
        # 把履行合同所必需错误用于营销推送等非必要场景
        legal_basis = '履行合同所必需'
        if purpose in ['营销推送', '广告投放', '数据分析', '产品优化']:
            status = '违法'
            note = '非必要信息不应使用"履行合同所必需"作为合法性基础'
        else:
            note = '合法性基础待核实'

    if idx in cross_border_unassessed_idx and cross_border == '是':
        status = '违法'
        note = note + '；出境未做安全评估' if note else '出境未做安全评估'

    if idx in unnotified_idx:
        notified = '否'
        status = '违法'
        note = note + '；未告知用户' if note else '未告知用户'

    if idx in no_separate_consent_idx and is_sensitive == '是':
        separate_consent = '否'
        status = '违法'
        note = note + '；敏感信息未获单独同意' if note else '敏感信息未获单独同意'

    if idx in retention_exceeded_idx:
        retention = '永久'
        status = '违法'
        note = note + '；保留期限超期' if note else '保留期限超期'

    if idx in normal_trap_idx:
        # 反直觉正常项：看起来有问题但实际合法
        if is_sensitive == '是' and separate_consent == '否':
            # 如果是履行合同所必需的敏感信息，不需单独同意
            if purpose in ['订单履约', '风控反欺诈'] and legal_basis == '履行合同所必需':
                separate_consent = '不适用'
                status = '合规'
                note = '履行合同所必需的敏感信息不需单独同意（合法边界）'
        elif cross_border == '是' and idx in cross_border_unassessed_idx:
            # 如果是员工个人数据出境，不适用个人信息出境安全评估
            if purpose == '风控反欺诈':  # 假设为员工数据
                status = '合规'
                note = '员工个人数据出境不适用安全评估（合法边界）'

    activities.append([f'DA{idx:03d}', purpose, cat, field_count, is_sensitive, legal_basis, purpose, '用户自行提供', storage, cross_border, notified, separate_consent, retention, status])

for a in activities:
    ws.append(a)
style_sheet(ws)
set_widths(ws, [10,14,12,12,14,18,14,14,16,12,14,14,12,14])

