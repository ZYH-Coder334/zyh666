def add_proj(ptype, amount, accept, client, invoiced, inv_full, secret_level, archived, name_prefix):
    """inv_full: 发票是否全额（True=全额，False=部分开票）"""
    global proj_seq
    proj_seq += 1
    pid = f'HT-2025-{proj_seq:04d}'
    contents = PROJ_CONTENT[ptype]
    projects.append([proj_seq, pid, f'{name_prefix}{ptype}项目', ptype, amount,
                     contents[proj_seq % len(contents)], accept, client, secret_level,
                     '已归档' if archived else '未归档'])
    acc = date.fromisoformat(accept)
    inv_date = (acc + timedelta(days=15))
    if inv_date > APPLY:
        inv_date = APPLY - timedelta(days=2)
    # 部分开票：发票金额为合同额的60-90%
    inv_amt = amount if inv_full else int(amount * (0.6 + (proj_seq % 4) * 0.1))
    invoices.append([proj_seq, pid, f'FP-2025-{proj_seq:05d}', client, inv_amt,
                     inv_date.strftime("%Y-%m-%d"), '已开具' if invoiced else '未开具',
                     '全额' if inv_full else '部分开票'])
    return pid


